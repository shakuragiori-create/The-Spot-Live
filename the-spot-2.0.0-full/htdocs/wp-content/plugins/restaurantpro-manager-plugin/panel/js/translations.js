(function() {
    var lang = window.RPLanguage || 'en';
    if (lang === 'en') return;

    var d = window.RPTranslations || {};

    function walk(n) {
        if (n.nodeType === 3) {
            var t = n.nodeValue.trim();
            if (d[t]) {
                n.nodeValue = n.nodeValue.replace(t, d[t]);
            }
            return;
        }

        if (n.nodeType !== 1) return;

        // Translate data-i18n attributes
        if (n.hasAttribute && n.hasAttribute('data-i18n')) {
            var key = n.getAttribute('data-i18n');
            if (d[key]) {
                // Only replace text content, preserve child elements
                var children = Array.from(n.childNodes);
                var hasElementChildren = children.some(function(c) { return c.nodeType === 1; });
                if (!hasElementChildren) {
                    n.textContent = d[key];
                }
            }
        }

        // Translate data-i18n-placeholder
        if (n.hasAttribute && n.hasAttribute('data-i18n-placeholder')) {
            var pkey = n.getAttribute('data-i18n-placeholder');
            if (d[pkey]) {
                n.setAttribute('placeholder', d[pkey]);
            }
        }

        // Translate common attributes
        ['placeholder', 'title', 'aria-label'].forEach(function(a) {
            if (n.hasAttribute && n.hasAttribute(a) && d[n.getAttribute(a)]) {
                n.setAttribute(a, d[n.getAttribute(a)]);
            }
        });

        Array.prototype.forEach.call(n.childNodes, walk);
    }

    walk(document.body);

    // Also translate dynamically added content
    var observer = new MutationObserver(function(mutations) {
        mutations.forEach(function(m) {
            m.addedNodes.forEach(function(node) {
                if (node.nodeType === 1) walk(node);
            });
        });
    });

    observer.observe(document.body, { childList: true, subtree: true });
})();
